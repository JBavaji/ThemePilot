import '../model/token_bundle.dart';
import 'base_emitter.dart';

/// Tailwind CSS (v3 & v4) Code Emitter
class TailwindEmitter implements PlatformEmitter {
  @override
  String get platformId => 'tailwind';

  @override
  String get targetFilePath => 'tailwind.config.js';

  @override
  GeneratedArtifact emit(TokenBundle bundle) {
    final c = bundle.colors;
    final r = bundle.radii;
    final typo = bundle.typography;

    final buffer = StringBuffer();
    buffer.writeln('// Generated by ThemePilot • $targetFilePath');
    buffer.writeln('// Archetype: ${bundle.archetype}');
    buffer.writeln('// Target: Tailwind CSS v3 & v4\n');
    buffer.writeln('/** @type {import(\'tailwindcss\').Config} */');
    buffer.writeln('module.exports = {');
    buffer.writeln('  darkMode: \'class\',');
    buffer.writeln('  content: [');
    buffer.writeln('    \'./src/**/*.{js,ts,jsx,tsx,html}\',');
    buffer.writeln('  ],');
    buffer.writeln('  theme: {');
    buffer.writeln('    extend: {');
    buffer.writeln('      colors: {');
    buffer.writeln('        scaffold: \'${c.scaffold}\',');
    buffer.writeln('        surface: {');
    buffer.writeln('          DEFAULT: \'${c.surface}\',');
    buffer.writeln('          dim: \'${c.surfaceDim}\',');
    buffer.writeln('          high: \'${c.surfaceHigh}\',');
    buffer.writeln('        },');
    buffer.writeln('        accent: {');
    buffer.writeln('          primary: \'${c.primary}\',');
    buffer.writeln('          secondary: \'${c.secondary}\',');
    buffer.writeln('          success: \'${c.success}\',');
    buffer.writeln('        },');
    buffer.writeln('        text: {');
    buffer.writeln('          primary: \'${c.textPrimary}\',');
    buffer.writeln('          muted: \'${c.textMuted}\',');
    buffer.writeln('          onAccent: \'${c.textOnAccent}\',');
    buffer.writeln('        },');
    buffer.writeln('      },');
    buffer.writeln('      borderRadius: {');
    buffer.writeln('        card: \'${r.card.toInt()}px\',');
    buffer.writeln('        container: \'${r.container.toInt()}px\',');
    buffer.writeln('        pill: \'${r.pill.toInt()}px\',');
    buffer.writeln('      },');
    buffer.writeln('      fontFamily: {');
    buffer.writeln('        display: [\'${typo.displayFont}\', \'sans-serif\'],');
    buffer.writeln('        sans: [\'${typo.bodyFont}\', \'sans-serif\'],');
    buffer.writeln('        mono: [\'${typo.codeFont}\', \'monospace\'],');
    buffer.writeln('      },');
    buffer.writeln('    },');
    buffer.writeln('  },');
    buffer.writeln('  plugins: [],');
    buffer.writeln('};');

    final content = buffer.toString();
    final lineCount = content.split('\n').length;

    return GeneratedArtifact(
      targetPlatform: platformId,
      relativeFilePath: targetFilePath,
      fileContent: content,
      lineCount: lineCount,
    );
  }
}
