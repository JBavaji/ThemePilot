import '../model/token_bundle.dart';
import 'base_emitter.dart';

/// Flutter Material 3 Code Emitter
class FlutterM3Emitter implements PlatformEmitter {
  @override
  String get platformId => 'flutter';

  @override
  String get targetFilePath => 'packages/theme/lib/src/theme_data.dart';

  @override
  GeneratedArtifact emit(TokenBundle bundle) {
    final c = bundle.colors;
    final r = bundle.radii;
    final s = bundle.spacing;

    final primaryHex = c.primary.replaceAll('#', '').toUpperCase();
    final secondaryHex = c.secondary.replaceAll('#', '').toUpperCase();
    final surfaceHex = c.surface.replaceAll('#', '').toUpperCase();
    final scaffoldHex = c.scaffold.replaceAll('#', '').toUpperCase();
    final successHex = c.success.replaceAll('#', '').toUpperCase();

    final buffer = StringBuffer();
    buffer.writeln('// Generated by ThemePilot • $targetFilePath');
    buffer.writeln('// Archetype: ${bundle.archetype}');
    buffer.writeln('// Target: Flutter Material 3 (Dart 3.x)\n');
    buffer.writeln("import 'package:flutter/material.dart';\n");

    buffer.writeln('/// Strongly-typed design tokens compiled by ThemePilot');
    buffer.writeln('abstract final class ThemePilotTokens {');
    buffer.writeln('  // Colors');
    buffer.writeln('  static const Color primary = Color(0xFF$primaryHex);');
    buffer.writeln('  static const Color secondary = Color(0xFF$secondaryHex);');
    buffer.writeln('  static const Color surface = Color(0xFF$surfaceHex);');
    buffer.writeln('  static const Color background = Color(0xFF$scaffoldHex);');
    buffer.writeln('  static const Color success = Color(0xFF$successHex);');
    buffer.writeln('');
    buffer.writeln('  // Radii');
    buffer.writeln('  static const BorderRadius radiusCard = BorderRadius.all(Radius.circular(${r.card}));');
    buffer.writeln('  static const BorderRadius radiusContainer = BorderRadius.all(Radius.circular(${r.container}));');
    buffer.writeln('  static const BorderRadius radiusPill = BorderRadius.all(Radius.circular(${r.pill}));');
    buffer.writeln('');
    buffer.writeln('  // 8dp Spatial Grid');
    buffer.writeln('  static const double gridBase = ${s.gridBase};');
    buffer.writeln('  static const double spaceSm = ${s.sm};');
    buffer.writeln('  static const double spaceMd = ${s.md};');
    buffer.writeln('  static const double spaceLg = ${s.lg};');
    buffer.writeln('  static const double spaceXl = ${s.xl};');
    buffer.writeln('}\n');

    buffer.writeln('/// Production Material 3 ThemeData Provider');
    buffer.writeln('abstract final class AppTheme {');
    buffer.writeln('  static ThemeData get darkTheme => ThemeData(');
    buffer.writeln('    useMaterial3: true,');
    buffer.writeln('    brightness: Brightness.dark,');
    buffer.writeln('    scaffoldBackgroundColor: ThemePilotTokens.background,');
    buffer.writeln('    colorScheme: const ColorScheme.dark(');
    buffer.writeln('      primary: ThemePilotTokens.primary,');
    buffer.writeln('      secondary: ThemePilotTokens.secondary,');
    buffer.writeln('      surface: ThemePilotTokens.surface,');
    buffer.writeln('    ),');
    buffer.writeln('    cardTheme: const CardTheme(');
    buffer.writeln('      color: ThemePilotTokens.surface,');
    buffer.writeln('      elevation: 0,');
    buffer.writeln('      shape: RoundedRectangleBorder(');
    buffer.writeln('        borderRadius: ThemePilotTokens.radiusCard,');
    buffer.writeln('      ),');
    buffer.writeln('    ),');
    buffer.writeln('  );');
    buffer.writeln('}');

    final content = buffer.toString();
    final lineCount = content.split('\n').length;

    return GeneratedArtifact(
      targetPlatform: platformId,
      relativeFilePath: targetFilePath,
      fileContent: content,
      lineCount: lineCount,
    );
  }
}
