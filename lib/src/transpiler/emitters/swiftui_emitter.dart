import '../model/token_bundle.dart';
import 'base_emitter.dart';

/// Apple SwiftUI (iOS 17+) Code Emitter
class SwiftUIEmitter implements PlatformEmitter {
  @override
  String get platformId => 'swiftui';

  @override
  String get targetFilePath => 'Sources/Theme/ThemePilotTokens.swift';

  @override
  GeneratedArtifact emit(TokenBundle bundle) {
    final c = bundle.colors;
    final r = bundle.radii;
    final s = bundle.spacing;

    final primaryRgb = ColorTokens.hexToRgbRatios(c.primary);
    final secondaryRgb = ColorTokens.hexToRgbRatios(c.secondary);
    final surfaceRgb = ColorTokens.hexToRgbRatios(c.surface);
    final scaffoldRgb = ColorTokens.hexToRgbRatios(c.scaffold);
    final successRgb = ColorTokens.hexToRgbRatios(c.success);

    final buffer = StringBuffer();
    buffer.writeln('// Generated by ThemePilot • $targetFilePath');
    buffer.writeln('// Archetype: ${bundle.archetype}');
    buffer.writeln('// Target: Apple SwiftUI (iOS 17+, macOS 14+)\n');
    buffer.writeln('import SwiftUI\n');

    buffer.writeln('/// Strongly-typed design tokens for SwiftUI');
    buffer.writeln('public enum ThemePilotTokens {');
    buffer.writeln('    // Color Tokens (Normalized RGB)');
    buffer.writeln('    public static let primary = Color(red: ${primaryRgb.r}, green: ${primaryRgb.g}, blue: ${primaryRgb.b})');
    buffer.writeln('    public static let secondary = Color(red: ${secondaryRgb.r}, green: ${secondaryRgb.g}, blue: ${secondaryRgb.b})');
    buffer.writeln('    public static let surface = Color(red: ${surfaceRgb.r}, green: ${surfaceRgb.g}, blue: ${surfaceRgb.b})');
    buffer.writeln('    public static let scaffold = Color(red: ${scaffoldRgb.r}, green: ${scaffoldRgb.g}, blue: ${scaffoldRgb.b})');
    buffer.writeln('    public static let success = Color(red: ${successRgb.r}, green: ${successRgb.g}, blue: ${successRgb.b})');
    buffer.writeln('');
    buffer.writeln('    // Corner Radii');
    buffer.writeln('    public static let cornerRadiusCard: CGFloat = ${r.card}');
    buffer.writeln('    public static let cornerRadiusContainer: CGFloat = ${r.container}');
    buffer.writeln('    public static let cornerRadiusPill: CGFloat = ${r.pill}');
    buffer.writeln('');
    buffer.writeln('    // 8dp Spatial Grid');
    buffer.writeln('    public static let spacingSm: CGFloat = ${s.sm}');
    buffer.writeln('    public static let spacingMd: CGFloat = ${s.md}');
    buffer.writeln('    public static let spacingLg: CGFloat = ${s.lg}');
    buffer.writeln('    public static let spacingXl: CGFloat = ${s.xl}');
    buffer.writeln('}');

    final content = buffer.toString();
    final lineCount = content.split('\n').length;

    return GeneratedArtifact(
      targetPlatform: platformId,
      relativeFilePath: targetFilePath,
      fileContent: content,
      lineCount: lineCount,
    );
  }
}
