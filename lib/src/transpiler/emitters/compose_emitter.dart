import '../model/token_bundle.dart';
import 'base_emitter.dart';

/// Android Jetpack Compose Material 3 Code Emitter
class ComposeM3Emitter implements PlatformEmitter {
  @override
  String get platformId => 'compose';

  @override
  String get targetFilePath => 'com/themepilot/theme/Theme.kt';

  @override
  GeneratedArtifact emit(TokenBundle bundle) {
    final c = bundle.colors;
    final r = bundle.radii;
    final s = bundle.spacing;

    final primaryHex = c.primary.replaceAll('#', '').toUpperCase();
    final secondaryHex = c.secondary.replaceAll('#', '').toUpperCase();
    final surfaceHex = c.surface.replaceAll('#', '').toUpperCase();
    final scaffoldHex = c.scaffold.replaceAll('#', '').toUpperCase();
    final successHex = c.success.replaceAll('#', '').toUpperCase();

    final buffer = StringBuffer();
    buffer.writeln('// Generated by ThemePilot • $targetFilePath');
    buffer.writeln('// Archetype: ${bundle.archetype}');
    buffer.writeln('// Target: Android Jetpack Compose (Material 3)\n');
    buffer.writeln('package com.themepilot.theme\n');
    buffer.writeln('import androidx.compose.material3.darkColorScheme');
    buffer.writeln('import androidx.compose.ui.graphics.Color');
    buffer.writeln('import androidx.compose.ui.unit.dp\n');

    buffer.writeln('object ThemePilotTokens {');
    buffer.writeln('    // Color Primitives');
    buffer.writeln('    val Primary = Color(0xFF$primaryHex)');
    buffer.writeln('    val Secondary = Color(0xFF$secondaryHex)');
    buffer.writeln('    val Surface = Color(0xFF$surfaceHex)');
    buffer.writeln('    val Background = Color(0xFF$scaffoldHex)');
    buffer.writeln('    val Success = Color(0xFF$successHex)');
    buffer.writeln('');
    buffer.writeln('    // Corner Radii');
    buffer.writeln('    val RadiusCard = ${r.card.toInt()}.dp');
    buffer.writeln('    val RadiusContainer = ${r.container.toInt()}.dp');
    buffer.writeln('    val RadiusPill = ${r.pill.toInt()}.dp');
    buffer.writeln('');
    buffer.writeln('    // 8dp Spatial Grid');
    buffer.writeln('    val SpaceSm = ${s.sm.toInt()}.dp');
    buffer.writeln('    val SpaceMd = ${s.md.toInt()}.dp');
    buffer.writeln('    val SpaceLg = ${s.lg.toInt()}.dp');
    buffer.writeln('    val SpaceXl = ${s.xl.toInt()}.dp');
    buffer.writeln('}\n');

    buffer.writeln('val ThemePilotDarkColorScheme = darkColorScheme(');
    buffer.writeln('    primary = ThemePilotTokens.Primary,');
    buffer.writeln('    secondary = ThemePilotTokens.Secondary,');
    buffer.writeln('    surface = ThemePilotTokens.Surface,');
    buffer.writeln('    background = ThemePilotTokens.Background,');
    buffer.writeln(')');

    final content = buffer.toString();
    final lineCount = content.split('\n').length;

    return GeneratedArtifact(
      targetPlatform: platformId,
      relativeFilePath: targetFilePath,
      fileContent: content,
      lineCount: lineCount,
    );
  }
}
